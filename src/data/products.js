// especifica existencias; la UI debe mostrar "Consultar disponibilidad".
//
// compatibilityType:
//  - "universal"       -> compatibility: []
//  - "vehicle-specific" -> compatibility: [{ brand, models }] (una marca)
//  - "multi-brand"      -> compatibility: [{ brand, models }, ...] (2+ marcas)

function universal(overrides) {
  return { compatibilityType: 'universal', compatibility: [], ...overrides };
}

function specific(brand, models, overrides) {
  return {
    compatibilityType: 'vehicle-specific',
    compatibility: [{ brand, models }],
    ...overrides,
  };
}

function multiBrand(entries, overrides) {
  return { compatibilityType: 'multi-brand', compatibility: entries, ...overrides };
}

